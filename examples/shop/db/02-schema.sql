-- 논리 복제 조건(@svc/replication precheck): 모든 표에 기본키(DB-T2), large object 없음(DB-T3).
-- 표 주인은 shop_owner, 앱 계정 app 은 읽기·쓰기만 (DB-14: 앱 계정 ≠ 표 주인 → 펜스 REVOKE 가 먹힌다).
SET ROLE shop_owner;
SET search_path = shop;

CREATE TABLE customers (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL UNIQUE,
  name        text NOT NULL,
  region      text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku         text NOT NULL UNIQUE,
  name        text NOT NULL,
  price_krw   integer NOT NULL CHECK (price_krw > 0),
  stock       integer NOT NULL DEFAULT 0,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE orders (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_ref   uuid NOT NULL UNIQUE,
  customer_id  bigint NOT NULL REFERENCES customers(id),
  status       text NOT NULL DEFAULT 'placed' CHECK (status IN ('placed','paid','shipped','cancelled')),
  total_krw    integer NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_idx ON orders(customer_id);
CREATE INDEX orders_created_idx ON orders(created_at DESC);

CREATE TABLE order_items (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id  bigint NOT NULL REFERENCES products(id),
  qty         integer NOT NULL CHECK (qty > 0),
  price_krw   integer NOT NULL
);
CREATE INDEX order_items_order_idx ON order_items(order_id);

RESET ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA shop TO app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA shop TO app;
